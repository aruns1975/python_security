#!/usr/bin/env python3
"""Generate local-development credentials for the three sample applications.

Creates random peppers, API keys and an application secret with `secrets.token_urlsafe`,
stores only peppered HMAC-SHA256 hashes in the called apps' configuration, and gives the
caller the matching raw outbound secrets, so that:

  mycaller-app  OUTBOUND_CALLED_APP__API_KEY            -> called-app hash (X-API-Key)
  mycaller-app  OUTBOUND_ANOTHER_CALLED_APP__*          -> another-called-app hash (X-Application-Id / X-Secret-Key)
  clients       MYCALLER_DASHBOARD_KEY / ORDERS_KEY     -> mycaller-app hashes (X-API-Key)

Files written (all gitignored, mode 0600):
  called-app/.env, another-called-app/.env, mycaller-app/.env, .client-credentials.env

No secret value is ever printed; only file paths and variable names. Existing files are
not overwritten unless --force is given (rotating invalidates all previously issued keys).

Usage: python3 scripts/generate_credentials.py [--force]
"""

import argparse
import hashlib
import hmac
import json
import os
import secrets
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

CALLED_APP_PORT = 48081
ANOTHER_CALLED_APP_PORT = 38081
LOCAL_HOST = "127.0.0.1"


def peppered_hash(value: str, pepper: str) -> str:
    """Must match `hash_api_key` in the apps: HMAC-SHA256(pepper, value), hex."""
    return hmac.new(pepper.encode(), value.encode(), hashlib.sha256).hexdigest()


def app_secret_hash(application_id: str, secret_key: str, pepper: str) -> str:
    """Must match `hash_secret_key` in another-called-app: HMAC-SHA256(pepper, id + NUL + secret), hex.
    Binding the ID means a hash copied onto another application's record never verifies."""
    return peppered_hash(f"{application_id}\0{secret_key}", pepper)


def new_secret() -> str:
    return secrets.token_urlsafe(32)  # 256 bits of entropy, URL/header/shell safe


def env_json(value: object) -> str:
    """Single-quoted compact JSON, valid both for pydantic-settings and for `source .env`."""
    text = json.dumps(value, separators=(",", ":"))
    assert "'" not in text
    return f"'{text}'"


def stage_private(path: Path, lines: list[str]) -> Path:
    """Write `lines` to a new temp file next to `path` and return the temp path.

    O_CREAT|O_EXCL|O_NOFOLLOW: never reuse or follow a pre-existing file or symlink. The file is
    created 0600 and fchmod'ed to 0600 (umask-independent) before any secret is written."""
    tmp = path.with_name(f".{path.name}.{secrets.token_hex(8)}.tmp")
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
    try:
        os.fchmod(fd, 0o600)
        with os.fdopen(fd, "w") as f:
            f.write("\n".join(lines) + "\n")
            f.flush()
            os.fsync(f.fileno())
    except BaseException:
        tmp.unlink(missing_ok=True)
        raise
    return tmp


def write_all_atomically(targets: dict[Path, list[str]]) -> None:
    """Stage every file first, then rename each into place with os.replace (atomic per file).
    If staging fails, nothing is replaced, so a failed run cannot leave mismatched credentials."""
    staged: dict[Path, Path] = {}
    try:
        for path, lines in targets.items():
            staged[path] = stage_private(path, lines)
    except BaseException:
        for tmp in staged.values():
            tmp.unlink(missing_ok=True)
        raise
    for path, tmp in staged.items():
        os.replace(tmp, path)
        print(f"wrote {path.relative_to(ROOT)}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--force", action="store_true", help="overwrite existing files (rotates every credential)")
    args = parser.parse_args()

    header = "# Generated by scripts/generate_credentials.py for LOCAL DEVELOPMENT. Never commit this file."

    # ---- called-app: accepts the caller's API key ----
    called_pepper = new_secret()
    called_app_api_key = new_secret()
    called_env = [
        header,
        f"SECURITY_INBOUND_API_KEY_PEPPER={called_pepper}",
        "SECURITY_INBOUND_API_KEYS="
        + env_json(
            [
                {
                    "key_id": "mycaller-app",
                    "key_hash": peppered_hash(called_app_api_key, called_pepper),
                    "subject": "svc:mycaller-app",
                    "authorities": ["ORDER_READ"],
                }
            ]
        ),
    ]

    # ---- another-called-app: accepts the caller's application ID + secret key ----
    another_pepper = new_secret()
    application_id = f"mycaller-app-{secrets.token_hex(4)}"  # identifier, not a secret
    secret_key = new_secret()
    another_env = [
        header,
        f"SECURITY_INBOUND_APP_CREDENTIALS_PEPPER={another_pepper}",
        "SECURITY_INBOUND_APP_CREDENTIALS="
        + env_json(
            [
                {
                    "application_id": application_id,
                    "secret_hash": app_secret_hash(application_id, secret_key, another_pepper),
                    "subject": "svc:mycaller-app",
                    "authorities": ["INVENTORY_READ"],
                }
            ]
        ),
    ]

    # ---- mycaller-app: own client keys (inbound) + outbound secrets ----
    mycaller_pepper = new_secret()
    dashboard_key = new_secret()
    orders_key = new_secret()
    services = {
        "CALLED_APP": {
            "service_id": "CALLED_APP",
            "base_url": f"http://{LOCAL_HOST}:{CALLED_APP_PORT}",
            "auth_type": "API_KEY",
            "credential_ref": "called-app",
            "allow_insecure_http": True,
        },
        "ANOTHER_CALLED_APP": {
            "service_id": "ANOTHER_CALLED_APP",
            "base_url": f"http://{LOCAL_HOST}:{ANOTHER_CALLED_APP_PORT}",
            "auth_type": "APP_CREDENTIALS",
            "credential_ref": "another-called-app",
            "allow_insecure_http": True,
        },
    }
    mycaller_env = [
        header,
        "",
        "# Inbound: API keys of MyCaller's own clients (hashes only).",
        f"SECURITY_INBOUND_API_KEY_PEPPER={mycaller_pepper}",
        "SECURITY_INBOUND_API_KEYS="
        + env_json(
            [
                {
                    "key_id": "dashboard-client",
                    "key_hash": peppered_hash(dashboard_key, mycaller_pepper),
                    "subject": "client:dashboard",
                    "authorities": ["ORDER_READ", "INVENTORY_READ", "DASHBOARD_READ"],
                },
                {
                    "key_id": "orders-client",
                    "key_hash": peppered_hash(orders_key, mycaller_pepper),
                    "subject": "client:orders",
                    "authorities": ["ORDER_READ"],
                },
            ]
        ),
        "",
        "# Outbound service registry.",
        "# LOCAL DEVELOPMENT ONLY: allow_insecure_http=true permits plain http to localhost.",
        "# Production MUST use https base URLs and omit allow_insecure_http.",
        f"SECURITY_OUTBOUND_SERVICES={env_json(services)}",
        "",
        "# Outbound secrets (EnvSecretStore: OUTBOUND_<CREDENTIAL_REF>__<KEY>).",
        f"OUTBOUND_CALLED_APP__API_KEY={called_app_api_key}",
        f"OUTBOUND_ANOTHER_CALLED_APP__APPLICATION_ID={application_id}",
        f"OUTBOUND_ANOTHER_CALLED_APP__SECRET_KEY={secret_key}",
    ]

    client_env = [
        "# Raw API keys for MyCaller's clients (LOCAL DEVELOPMENT ONLY). Never commit this file.",
        "# Usage: source this file, then pass the header from a 0600 file rather than on the command line",
        "# (argv is visible in `ps`): printf 'X-API-Key: %s\\n' \"$MYCALLER_DASHBOARD_KEY\" > h; curl -H @h ...",
        f"MYCALLER_DASHBOARD_KEY={dashboard_key}",
        f"MYCALLER_ORDERS_KEY={orders_key}",
    ]

    targets = {
        ROOT / "called-app" / ".env": called_env,
        ROOT / "another-called-app" / ".env": another_env,
        ROOT / "mycaller-app" / ".env": mycaller_env,
        ROOT / ".client-credentials.env": client_env,
    }
    if not args.force:
        existing = [p for p in targets if p.exists()]
        if existing:
            sys.exit(f"Refusing to overwrite {', '.join(str(p.relative_to(ROOT)) for p in existing)} (use --force)")
    # Every value above was generated before any file is touched.
    write_all_atomically(targets)
    print("Client key variables: MYCALLER_DASHBOARD_KEY (all authorities), MYCALLER_ORDERS_KEY (ORDER_READ only)")


if __name__ == "__main__":
    main()
